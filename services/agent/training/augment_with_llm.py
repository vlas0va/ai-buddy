"""Augment the intent dataset with paraphrases from any OpenAI-compatible model (e.g. a local Ollama on the laptop).

python training/augment_with_llm.py --per-intent 15        # needs LLM_BASE_URL and LLM_MODEL
Writes eval/intents/augmented.yaml for review; after a human check merge it into train.yaml and run `make train`.
Phrases that collide with the held-out test set are dropped so the reported accuracy stays honest.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agent.config import REPO_ROOT  # noqa: E402
from agent.llm.openai_compat import OpenAICompatClient  # noqa: E402
from agent.text import normalize  # noqa: E402

PROMPT = (
    "Ты помогаешь собрать обучающие данные для классификатора намерений чат-бота стажёра. Намерение: «{intent}». "
    "Примеры: {examples}. Напиши {n} новых разных коротких формулировок по-русски, как пишет стажёр в чате "
    "(разговорный стиль, без нумерации). Ответ — JSON-массив строк."
)


def augment(
    client: OpenAICompatClient, train: dict[str, list[str]], test: dict[str, list[str]], per_intent: int
) -> dict:
    banned = {normalize(t) for texts in [*train.values(), *test.values()] for t in texts}
    out: dict[str, list[str]] = {}
    for intent, examples in train.items():
        msg = PROMPT.format(intent=intent, examples="; ".join(examples[:8]), n=per_intent)
        raw = client.complete([{"role": "user", "content": msg}]).content
        try:
            phrases = json.loads(raw[raw.index("[") : raw.rindex("]") + 1])
        except ValueError:
            phrases = [line.strip("-• \t") for line in raw.splitlines() if line.strip()]
        fresh = [p for p in (str(x).strip() for x in phrases) if p and normalize(p) not in banned]
        out[intent] = fresh[:per_intent]
    return out


def main(argv: list[str] | None = None, client: OpenAICompatClient | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-intent", type=int, default=15)
    ap.add_argument("--out", default=str(REPO_ROOT / "eval" / "intents" / "augmented.yaml"))
    args = ap.parse_args(argv)
    client = client or OpenAICompatClient(
        os.environ.get("LLM_BASE_URL", ""),
        os.environ.get("LLM_API_KEY", ""),
        os.environ.get("LLM_MODEL", ""),
        timeout_s=120,
        temperature=0.9,
    )
    load = lambda name: yaml.safe_load((REPO_ROOT / "eval" / "intents" / name).read_text(encoding="utf-8"))  # noqa: E731
    result = augment(client, load("train.yaml"), load("test.yaml"), args.per_intent)
    Path(args.out).write_text(
        "# Paraphrases generated by an LLM — review before merging into train.yaml\n"
        + yaml.safe_dump(result, allow_unicode=True, sort_keys=False),
        encoding="utf-8",
    )
    print(f"{sum(map(len, result.values()))} phrases → {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
