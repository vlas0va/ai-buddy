def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def arr(values):
    return "ARRAY[" + ", ".join(q(v) for v in values) + "]::text[]"


